    @Slot(str)
    def connect_piezo(self, side: str):
        """Connects or disconnects a piezo controller on a worker thread."""
        if self._shutdown_requested or self._pending_piezo_operation_close:
            logger.info("Ignoring %s piezo operation while application close is pending.", side)
            return
        if side not in {"left", "right"} or side in self._piezo_operations_in_flight:
            return
        if self._alignment_hardware_transition_blocked():
            logger.info("Ignoring %s piezo operation while alignment owns the hardware.", side)
            return
        if side == "left":
            piezo = self.piezo_left
            port = getattr(piezo, "discovered_port", None) or self.config.instruments.piezo_left_serial
        else:
            piezo = self.piezo_right
            port = getattr(piezo, "discovered_port", None) or self.config.instruments.piezo_right_serial

        if not piezo:
            logger.error(f"Cannot connect {side} piezo: object is None.")
            return

        do_connect = not piezo.is_connected()

        usb_serial = (
            self.config.instruments.piezo_left_usb_serial
            if side == "left"
            else self.config.instruments.piezo_right_usb_serial
        )
        worker = PiezoConnectionWorker(piezo, side, port, do_connect, usb_serial=usb_serial)
        # A QRunnable may be released in a pool thread. Its GUI-affine signal
        # QObject needs native GUI ownership until the queued result is read.
        worker.signals.setParent(self)
        worker.signals.connection_succeeded.connect(worker.signals.deleteLater)
        worker.signals.disconnection_succeeded.connect(worker.signals.deleteLater)
        worker.signals.connection_failed.connect(worker.signals.deleteLater)

        # Connect signals to the main thread's *slots*
        worker.signals.connection_succeeded.connect(self.piezo_connection_succeeded)
        worker.signals.disconnection_succeeded.connect(self._on_piezo_disconnection_success)
        worker.signals.connection_failed.connect(self.piezo_connection_failed)

        # Reserve the controller before dispatch so Refresh cannot replace it.
        self._piezo_operations_in_flight.add(side)
        self._update_piezo_action(side)
        if not do_connect:
            self._sync_alignment_hardware()

        QThreadPool.globalInstance().start(worker)

    def _update_piezo_action(self, side: str):
        """Render truthful connection state with the CT400/PM5020 menu icon convention."""
        action = self.piezo_connect_left_action if side == "left" else self.piezo_connect_right_action
        piezo = self.piezo_left if side == "left" else self.piezo_right
        title = side.capitalize()
        connected = piezo is not None and piezo.is_connected()
        if side in self._piezo_operations_in_flight:
            text = f"{'Disconnecting' if connected else 'Connecting'} {title}..."
            icon, enabled = ":/icons/spinner.svg", False
        elif self._piezo_discovery_pending:
            text, icon, enabled = f"Finding {title} Piezo...", ":/icons/spinner.svg", False
        elif piezo is None:
            text, icon, enabled = f"{title} Piezo (Not Found)", ":/icons/connect.svg", False
        else:
            text = f"{'Disconnect' if connected else 'Connect'} {title} Piezo"
            icon, enabled = (":/icons/disconnect.svg" if connected else ":/icons/connect.svg"), True
        action.setText(text)
        action.setIcon(QIcon(icon))
        action.setChecked(connected)
        action.setEnabled(enabled and not self._pending_piezo_operation_close)
        action.setStatusTip(
            "Connected to the configured controller."
            if connected
            else "Configured serial port detected; identity is verified only by an explicit Connect."
            if piezo is not None
            else "Configured serial port not detected; use Refresh Instruments after connecting hardware."
        )

