    def _alignment_hardware_transition_blocked(self) -> bool:
        panel = getattr(self, "_alignment_tab", None)
        return bool(
            self._ct400_operation_state is CT400OperationState.ALIGNMENT
            or (panel is not None and (panel._active_mode is not None or panel._ct400_operation_state == "ALIGNMENT"))
        )

    def _sync_alignment_hardware(self):
        """Keep the alignment panel bound only to currently usable hardware."""
        panel = getattr(self, "_alignment_tab", None)
        if panel is None:
            return
        panel.set_start_authorizer(self._is_alignment_operation_authorized)
        if self._alignment_hardware_transition_blocked():
            panel._update_control_availability()
            return
        ready = (
            self.ct400_device is not None
            and self.piezo_left is not None
            and self.piezo_right is not None
            and self.piezo_left.is_connected()
            and self.piezo_right.is_connected()
            and not self._piezo_operations_in_flight
            and not self._pending_piezo_operation_close
            and not self._alignment_hardware_transition_blocked()
        )
        if ready:
            panel.set_hardware(self.ct400_device, self.piezo_left, self.piezo_right)
        else:
            panel.clear_hardware()

    def _ct400_lease_available_for_new_operation(self) -> bool:
        """Preflight the shared CT400 owner before dispatching native work."""
        return (
            not self._shutdown_requested
            and self._ct400_operation_state is CT400OperationState.IDLE
            and self._ct400_operation_lease is None
            and not self._ct400_scan_state_uncertain
            and self.device_lease_registry.snapshot()[0].owner is None
        )

    def _is_alignment_operation_authorized(self) -> bool:
        """Authorize alignment only for simulation or the explicitly connected physical input."""
        dialog = self._ct400_campaign_dialog
        if dialog is not None and dialog.active:
            return False
        if not self._ct400_lease_available_for_new_operation():
            return False
        if self._ct400_scan_state_uncertain or self._ct400_recovery_disconnect_completed:
            return False
        device = self.ct400_device
        if isinstance(device, DummyCT400):
            return (
                self._ct400_is_configured_simulation()
                and self.alignment_tab is not None
                and self.alignment_tab.ct400 is device
            )
        if not isinstance(device, CT400) or self.alignment_tab is None or self.alignment_tab.ct400 is not device:
            return False
        captured_input = self._ct400_connected_laser_input
        if (
            not self._ct400_connection_configured
            or captured_input is None
            or captured_input is not self._ct400_cleanup_laser_input
        ):
            return False
        try:
            selected_input = LaserInput(self.alignment_tab.input_port_combo.currentData())
        except (TypeError, ValueError):
            return False
        return selected_input is captured_input

    @Slot(str)
    def _on_piezo_connection_success(self, side: str):
        logger.info(f"{side.capitalize()} Piezo connected successfully.")
        self._complete_piezo_operation(side)
        self.statusBar().showMessage(f"{side.capitalize()} Piezo connected.", 3000)

    @Slot(str)
    def _on_piezo_disconnection_success(self, side: str):
        logger.info(f"{side.capitalize()} Piezo disconnected.")
        self._complete_piezo_operation(side)
        self.statusBar().showMessage(f"{side.capitalize()} Piezo disconnected.", 3000)

    @Slot(str, str)
    def _on_piezo_connection_failed(self, side: str, error_message: str):
        logger.error(f"Failed to connect {side} piezo: {error_message}")
        self._complete_piezo_operation(side)
        QMessageBox.critical(self, f"{side.capitalize()} Piezo Error", f"Operation failed: {error_message}")

    def _complete_piezo_operation(self, side: str) -> bool:
        """Release one side's operation ownership and refresh dependent UI."""
        was_in_flight = side in self._piezo_operations_in_flight
        if was_in_flight:
            self._piezo_operations_in_flight.remove(side)
        self._update_piezo_action(side)
        if self._pending_piezo_operation_close:
            if self._alignment_tab is not None:
                self._alignment_tab.clear_hardware()
            if was_in_flight:
                self._resume_close_after_piezo_operation()
        else:
            self._sync_alignment_hardware()
        return was_in_flight

    def _resume_close_after_piezo_operation(self):
        """Schedule close only after all piezo workers release their controllers."""
        if self._pending_piezo_operation_close and not self._piezo_operations_in_flight:
            QTimer.singleShot(0, self, self.close)

    @Slot(str, str)
    def _on_ct400_status_updated(self, state_name: str, message: str):
        """Updates the status bar from the CT400 init worker."""
        try:
            state = CT400Status[state_name.upper()]
        except KeyError:
            state = CT400Status.UNKNOWN

        self._update_ct400_visuals(state=state, message=message)

    @Slot(int, str, str)
    def _on_ct400_attempt_status_updated(self, attempt_id: int, state_name: str, message: str):
        if attempt_id != self._active_ct400_init_attempt_id or self._pending_init_close:
            logger.debug("Ignoring stale CT400 initialization status for attempt %s.", attempt_id)
            return
        self._on_ct400_status_updated(state_name, message)

    @Slot(AbstractCT400)
    def _on_ct400_initialized(self, device: AbstractCT400):
        """
        Receives the initialized CT400 device (real or dummy) from the worker.
        This slot is now responsible for populating the rest of the UI
        that depends on the CT400.
        """
        logger.info(f"CT400 initialization finished. Received device: {type(device)}")
        if device is not self.ct400_device and any(
            item.resource is DeviceResource.CT400 and item.owner == "synchronized-acquisition"
            for item in self.device_lease_registry.snapshot()
        ):
            self._defer_ct400_device_replacement(device)
            return
        if device is not self.ct400_device and self._ct400_operation_state in (
            CT400OperationState.CONNECTING,
            CT400OperationState.DISCONNECTING,
            CT400OperationState.SCANNING,
            CT400OperationState.MONITORING,
        ):
            logger.warning("Deferring CT400 replacement until the active operation releases its device.")
            self._defer_ct400_device_replacement(device)
            return
        if device is not self.ct400_device and self._ct400_device_has_unresolved_laser_state():
            self._defer_ct400_device_replacement(device)
            self._apply_pending_ct400_device_replacement()
            return
        if self._alignment_hardware_transition_blocked() and device is not self.ct400_device:
            logger.warning("Ignoring CT400 replacement while alignment owns the current hardware.")
            if isinstance(device, CT400):
                try:
                    device.close()
                except Exception:
                    logger.exception("Could not release rejected CT400 resources.")
            return
        old_device = self.ct400_device
        self.ct400_device = device
        if old_device is not device:
            self._ct400_connection_operation_token += 1
            self._ct400_connected_laser_input = None
            self._ct400_cleanup_laser_input = None
            self._ct400_connection_configured = False
            self._ct400_scan_state_uncertain = False
            self._ct400_recovery_input_matches = True
            self._ct400_recovery_disconnect_completed = False

        # Now that the device exists, pass it to the control panels
        is_configured_simulation = self._ct400_is_configured_simulation() and isinstance(self.ct400_device, DummyCT400)
        if self._control_panel is not None:
            self._control_panel.set_instrument(self.ct400_device, simulated=is_configured_simulation)
        self.histogram_control.set_instrument(self.ct400_device, simulated=is_configured_simulation)

        # Update UI visuals based on whether the device is real or dummy
        is_real_ct400 = isinstance(self.ct400_device, CT400)
        is_simulated_ct400 = is_configured_simulation and isinstance(self.ct400_device, DummyCT400)
        # DummyCT400 exposes the same scan interface and is safe to operate in
        # development mode. Keep it unavailable to connection controls, but
        # allow scans and label their results as simulated below.
        self._set_scan_connected_laser_input(None)
        self.histogram_control.set_connected_laser_input(None)
        if is_simulated_ct400:
            if self._control_panel is not None:
                self._control_panel.on_instrument_connected(True)
            self.histogram_control.on_instrument_connected(True)

        if old_device is not None and old_device is not device and isinstance(old_device, CT400):
            try:
                old_device.close()
            except Exception:
                logger.exception("Could not close replaced CT400 device.")

        if is_real_ct400:
            self._update_ct400_visuals(state=CT400Status.DISCONNECTED, message="CT400 Ready (Disconnected)")
        else:
            # The status was already set to UNAVAILABLE by the worker's error
            pass

        if is_simulated_ct400:
            self._refresh_global_status()

        self._sync_alignment_hardware()

    def _ct400_device_has_unresolved_laser_state(self) -> bool:
        return bool(
            self._ct400_scan_state_uncertain
            or self._ct400_connection_configured
            or self._ct400_cleanup_laser_input is not None
            or self._ct400_connected_laser_input is not None
            or self.is_ct400_connected_state
        )

    def _ct400_is_configured_simulation(self) -> bool:
        return self.config.instruments.ct400_backend == "simulation"

    def _defer_ct400_device_replacement(self, device: AbstractCT400):
        previous = self._pending_ct400_device_replacement
        if previous is not None and previous is not device and isinstance(previous, CT400):
            try:
                previous.close()
            except Exception:
                logger.exception("Could not close superseded pending CT400 device.")
        self._pending_ct400_device_replacement = device
        if self._ct400_operation_state is CT400OperationState.IDLE:
            self._ct400_connection_operation_token += 1
            self._ct400_connected_laser_input = None
            self._set_scan_connected_laser_input(None)
            self.histogram_control.set_connected_laser_input(None)
            if self._ct400_scan_state_uncertain:
                if self._ct400_recovery_disconnect_completed:
                    state = CT400Status.RECOVERY_CONFIRMATION_REQUIRED
                    message = (
                        "Recovery Disconnect command returned; it does not independently confirm physical "
                        "safe-state. Follow the approved procedure, then explicitly confirm safe-state."
                    )
                else:
                    state = CT400Status.SCAN_STATE_UNCERTAIN
                    message = "CT400 scan state is uncertain; use operator-controlled recovery before replacement."
                self._update_ct400_visuals(state, message)
            elif self._ct400_cleanup_laser_input is not None:
                self._update_ct400_visuals(
                    CT400Status.DISCONNECT_UNCONFIRMED,
                    f"Replacement pending; disconnect the previously configured input "
                    f"{self._ct400_cleanup_laser_input.name} first.",
                )
            else:
                self._update_ct400_visuals(
                    CT400Status.DISCONNECT_UNCONFIRMED,
                    "CT400 state is uncertain and its configured input is unknown. "
                    "Follow the approved laboratory safe-state procedure.",
                )

    def _apply_pending_ct400_device_replacement(self):
        replacement = self._pending_ct400_device_replacement
        if (
            replacement is None
            or self._ct400_operation_state is not CT400OperationState.IDLE
            or self.device_lease_registry.snapshot()[0].owner is not None
        ):
            return
        if self._ct400_device_has_unresolved_laser_state():
            self._defer_ct400_device_replacement(replacement)
            return
        self._pending_ct400_device_replacement = None
        self._on_ct400_initialized(replacement)

    def _begin_lazy_init(self):
        """Starts all slow hardware initializations on background threads."""
        if self._shutdown_requested or self._lazy_init_started:
            return
        self._lazy_init_started = True
        logger.info("Starting lazy initialization of hardware...")

        # Optional piezo discovery is passive and only starts when a port is
        # configured. Hardware-free installations should launch without a task.
        if any(
            (
                self.config.instruments.piezo_left_serial,
                self.config.instruments.piezo_right_serial,
                self.config.instruments.piezo_left_usb_serial,
                self.config.instruments.piezo_right_usb_serial,
            )
        ):
            self._init_piezos_lazy()

        # CT400 initialization remains asynchronous.
        self._init_ct400_lazy()

        # Start the proprietary Vimba system only when a physical camera is
        # explicitly configured. Simulated cameras use the same panel workflow
        # and remain available on driver-free development machines.
        needs_vimba = any(cam.enabled and cam.backend == "vimba" for cam in self.config.cameras.values())
        if needs_vimba:
            # SDK startup can take seconds and MUST NOT run on the Qt GUI thread.
            # Camera workers start only after the startup worker has fully retired.
            self._start_vimbasystem()
        else:
            self._init_cameras_lazy()

    def _init_ct400_lazy(self):
        """Start one owned CT400 initialization attempt on a background thread."""
        if self._shutdown_requested or self._pending_init_close:
            logger.info("Skipping CT400 initialization while application close is pending.")
            return
        if self._active_ct400_init_attempt_id is not None:
            logger.info("CT400 initialization is already in progress; suppressing duplicate attempt.")
            return
        if (
            self._ct400_operation_state is not CT400OperationState.IDLE
            or self._ct400_device_has_unresolved_laser_state()
            or self._alignment_hardware_transition_blocked()
        ):
            self.statusBar().showMessage("Resolve the current CT400 operation or recovery state before retrying.", 5000)
            return
        self._ct400_init_attempt_id += 1
        attempt_id = self._ct400_init_attempt_id
        self._active_ct400_init_attempt_id = attempt_id
        logger.info("Starting lazy initialization of CT400...")
        worker = CT400InitWorker(config=self.config)
        terminal_outcome: list[CT400InitOutcome | None] = [None]
        worker.initialization_completed.connect(
            lambda outcome: terminal_outcome.__setitem__(0, outcome),
            Qt.ConnectionType.DirectConnection,
        )
        worker.status_updated.connect(
            lambda state, message: self._ct400_attempt_status.emit(attempt_id, state, message)
        )
        task = TaskRunner(worker)
        self.ct400_task = task
        task.worker_thread.finished.connect(
            lambda task=task, attempt_id=attempt_id, outcome=terminal_outcome: self._ct400_init_task_finished.emit(
                attempt_id, task, outcome[0]
            )
        )
        self._track_init_task(task)
        self._update_ct400_retry_action()
        task.start()

    @Slot(int, object, object)
    def _on_ct400_init_task_finished(self, attempt_id: int, task=None, outcome: CT400InitOutcome | None = None):
        """Transfer an outcome only after its worker thread has released ownership."""
        if task is None:
            return
        if attempt_id <= self._ct400_latest_finished_attempt_id:
            self._dispose_unowned_ct400_candidate(outcome.device if outcome is not None else None)
            return
        if attempt_id != self._active_ct400_init_attempt_id:
            logger.warning("Ignoring CT400 completion for inactive attempt %s.", attempt_id)
            self._dispose_unowned_ct400_candidate(outcome.device if outcome is not None else None)
            return
        if self.ct400_task is task:
            self.ct400_task = None
        self._ct400_latest_finished_attempt_id = attempt_id
        if outcome is None:
            outcome = CT400InitOutcome(
                device=None,
                state_name="UNAVAILABLE",
                message="CT400 initialization ended without a terminal result. Retry is available.",
            )
        if self._pending_init_close:
            self._dispose_unowned_ct400_candidate(outcome.device)
            self._active_ct400_init_attempt_id = None
            self._update_ct400_retry_action()
            return
        if outcome.device is None:
            try:
                terminal_state = CT400Status[outcome.state_name.upper()]
            except KeyError:
                terminal_state = CT400Status.UNAVAILABLE
            self._update_ct400_visuals(terminal_state, outcome.message)
        else:
            if outcome.state_name.upper() == "UNAVAILABLE":
                self._update_ct400_visuals(CT400Status.UNAVAILABLE, outcome.message)
            self._on_ct400_initialized(outcome.device)
            if outcome.state_name.upper() == "SIMULATED":
                self.statusBar().showMessage(outcome.message, 5000)
        self._active_ct400_init_attempt_id = None
        self._update_ct400_retry_action()

    def _dispose_unowned_ct400_candidate(self, device: AbstractCT400 | None) -> None:
        if not isinstance(device, CT400) or self._ct400_device_is_owned(device):
            return
        if device in self._ct400_disposed_candidates:
            return
        self._ct400_disposed_candidates.add(device)
        try:
            device.close()
        except Exception:
            logger.exception("Could not release an unowned stale CT400 initialization result.")

    def _ct400_device_is_owned(self, device: CT400) -> bool:
        if device is self.ct400_device or device is self._pending_ct400_device_replacement:
            return True
        for panel in (self._control_panel, self.histogram_control, self._alignment_tab):
            if panel is not None and getattr(panel, "ct400", None) is device:
                return True
        return False

    def _update_ct400_retry_action(self) -> None:
        action = getattr(self, "ct400_retry_action", None)
        if action is None:
            return
        eligible_device = self.ct400_device is None or isinstance(self.ct400_device, DummyCT400)
        physical_backend = self.config.instruments.ct400_backend != "simulation"
        allowed = (
            eligible_device
            and physical_backend
            and self._active_ct400_init_attempt_id is None
            and not self._pending_init_close
            and self._ct400_operation_state is CT400OperationState.IDLE
            and not self._ct400_device_has_unresolved_laser_state()
            and not self._alignment_hardware_transition_blocked()
        )
        action.setEnabled(allowed)

    @Slot()
    def _retry_ct400_initialization(self) -> None:
        if self._pending_init_close:
            logger.info("Ignoring CT400 retry while application close is pending.")
            return
        if not (self.ct400_device is None or isinstance(self.ct400_device, DummyCT400)):
            self.statusBar().showMessage("CT400 is already initialized; retry is unavailable.", 5000)
            return
        if self._active_ct400_init_attempt_id is not None:
            self.statusBar().showMessage("CT400 initialization is already in progress.", 5000)
            return
        if (
            self._ct400_operation_state is not CT400OperationState.IDLE
            or self._ct400_device_has_unresolved_laser_state()
            or self._alignment_hardware_transition_blocked()
        ):
            self.statusBar().showMessage("Resolve the current CT400 operation or recovery state before retrying.", 5000)
            return
        self._update_ct400_visuals(CT400Status.UNKNOWN, "Operator requested CT400 initialization retry.")
        self._init_ct400_lazy()

    def _init_piezos_lazy(self):
        """Initializes the Piezo controllers on a background thread."""
        if self._shutdown_requested:
            return
        if self._pending_piezo_operation_close:
            logger.info("Skipping piezo initialization while application close is pending.")
            return
        if self._pending_init_close:
            logger.info("Skipping piezo initialization while application close is pending.")
            return
        if self._piezo_operations_in_flight:
            logger.info("Skipping piezo discovery while a piezo connection operation is active.")
            return
        if self._alignment_hardware_transition_blocked():
            logger.info("Skipping piezo discovery while alignment owns the hardware.")
            return
        if self.piezo_task is not None and self.piezo_task.worker_thread.isRunning():
            logger.info("Skipping duplicate piezo discovery while another task is running.")
            return
        logger.info("Starting passive discovery of configured Piezo serial ports...")
        self._piezo_discovery_pending = True
        self._update_piezo_action("left")
        self._update_piezo_action("right")

        worker = PiezoInitWorker(config=self.config.instruments)

        # Connect specific data signals
        worker.piezos_initialized.connect(self._on_piezos_initialized)
        worker.initialization_failed.connect(self._on_piezo_init_failed)

        # TaskRunner owns the worker and thread for this one-shot operation.
        task = TaskRunner(worker)
        self.piezo_task = task
        task.worker_thread.finished.connect(lambda task=task: self._piezo_init_task_finished.emit(task))
        self._track_init_task(task)
        task.start()

    def _track_init_task(self, task: TaskRunner):
        """Own an initialization task until its thread reaches its final boundary."""
        self._init_tasks.add(task)
        task.worker_thread.finished.connect(lambda task=task: self._init_task_thread_finished.emit(task))

    @Slot(object)
    def _on_init_task_thread_finished(self, task):
        """Release exactly the initialization task whose thread finished."""
        if task not in self._init_tasks:
            return
        self._init_tasks.remove(task)
        if self._pending_init_close and not self._init_tasks:
            logger.info("All initialization tasks finished; resuming deferred application close.")
            QTimer.singleShot(0, self, self.close)

    @Slot(object)
    def _on_piezo_init_task_finished(self, task):
        """Clear only the piezo task whose thread just finished."""
        if self.piezo_task is task:
            self.piezo_task = None

    def _start_vimbasystem(self):
        """Start the proprietary Vimba SDK off the GUI thread.

        A Vimba context is published to MainWindow only at the final QThread
        boundary, never while native startup/discovery is still in progress.
        """
        if self._shutdown_requested or self._pending_init_close:
            return
        if self.vmb_instance is not None or self._vimba_init_task is not None:
            logger.info("VmbSystem already active or startup in progress.")
            return
        if not VIMBA_AVAILABLE:
            logger.warning("Vimba camera support is not installed; physical cameras are unavailable.")
            self._init_cameras_lazy()
            return

        logger.info("Scheduling asynchronous VmbSystem startup...")
        worker = VimbaSystemInitWorker(VmbSystem.get_instance)
        outcome_holder: list[VimbaSystemInitOutcome | None] = [None]
        # Collect the immutable result synchronously on the emitting thread.
        # A queued result callback may otherwise be processed after finished,
        # racing closeEvent's native-resource cleanup.
        worker.initialization_completed.connect(
            lambda outcome: outcome_holder.__setitem__(0, outcome),
            Qt.ConnectionType.DirectConnection,
        )
        task = TaskRunner(worker)
        self._vimba_init_task = task
        # This task has a dedicated terminal handler: it must adopt the native
        # context BEFORE removing the task from the close-defer ownership set.
        self._init_tasks.add(task)
        task.worker_thread.finished.connect(
            lambda task=task, holder=outcome_holder: self._vimba_init_thread_finished.emit(task, holder[0])
        )
        task.start()

    @Slot(object, object)
    def _on_vimba_init_thread_finished(self, task: TaskRunner, outcome: VimbaSystemInitOutcome | None):
        """Adopt an initialized SDK context only after the worker thread exits."""
        if task is not self._vimba_init_task:
            logger.warning("Ignoring stale VmbSystem initialization result.")
            return
        self._vimba_init_task = None
        if outcome is not None and outcome.instance is not None:
            self.vmb_instance = outcome.instance
            logger.info("VmbSystem startup completed; system context is active.")
        else:
            message = outcome.error if outcome is not None else "Startup worker returned no result"
            logger.error("VmbSystem unavailable: %s", message)
            self.statusBar().showMessage("Vimba X startup failed; physical cameras are unavailable.", 10000)

        # Do not remove this ownership guard earlier: a close requested during
        # the native SDK call must still defer camera and VmbSystem teardown.
        self._init_tasks.discard(task)
        if self._shutdown_requested or self._pending_init_close:
            if self._pending_init_close and not self._init_tasks:
                QTimer.singleShot(0, self, self.close)
            return
        self._init_cameras_lazy()

    def _cleanup_vimbasystem(self):
        """Exits the VimbaSystem context cleanly."""
        if self.vmb_instance:
            logger.info("Attempting to exit VmbSystem...")
            try:
                self.vmb_instance.__exit__(None, None, None)
                logger.info("VmbSystem exited successfully.")
            except VmbSystemError:
                logger.exception("Failed to exit VmbSystem")
            except Exception as e:
                logger.critical(f"Unexpected error exiting VmbSystem: {e}", exc_info=True)
            finally:
                self.vmb_instance = None

    def _load_defaults_from_config(self):
        """Load default values from config into UI elements."""
        logger.debug("Loading UI defaults from configuration...")
        try:
            if self._control_panel is not None:
                self._load_scan_defaults_from_config()
            if hasattr(self, "histogram_control") and self.histogram_control:
                hist_defaults = self.config.histogram_defaults
                self.histogram_control.wavelength_input.setText(str(hist_defaults.wavelength_nm))
                self.histogram_control.laser_power.setText(str(hist_defaults.laser_power))
                power_unit_idx_hist = self.histogram_control.power_unit.findText(hist_defaults.power_unit)
                if power_unit_idx_hist != -1:
                    self.histogram_control.power_unit.setCurrentIndex(power_unit_idx_hist)
                for i in range(self.histogram_control.input_port.count()):
                    if self.histogram_control.input_port.itemData(i).value == hist_defaults.input_port:
                        self.histogram_control.input_port.setCurrentIndex(i)
                        break
                if hasattr(self.histogram_control, "detector_cbs"):
                    for i, checkbox in enumerate(self.histogram_control.detector_cbs):
                        is_enabled = getattr(hist_defaults, f"detector_{i + 1}_enabled", False)
                        checkbox.setChecked(is_enabled)
        except Exception:
            logger.exception("Error loading defaults from config")
            self.statusBar().showMessage("Error loading defaults from config", 5000)

    def _load_scan_defaults_from_config(self) -> None:
        """Populate scan-only defaults without resetting the monitor UI."""
        panel = self._control_panel
        if panel is None:
            return
        defaults = self.config.scan_defaults
        panel.initial_wl.setText(str(defaults.start_wavelength_nm))
        panel.final_wl.setText(str(defaults.end_wavelength_nm))
        panel.resolution.setText(str(defaults.resolution_pm))
        panel.motor_speed.setText(str(defaults.speed_nm_s))
        panel.laser_power.setText(str(defaults.laser_power))
        unit_idx = panel.power_unit.findText(defaults.power_unit)
        if unit_idx != -1:
            panel.power_unit.setCurrentIndex(unit_idx)
        for i in range(panel.input_port.count()):
            if panel.input_port.itemData(i).value == defaults.input_port:
                panel.input_port.setCurrentIndex(i)
                break
        enabled = set(self.settings.scan_detectors())
        for detector, checkbox in panel.scan_detector_cbs.items():
            checkbox.setChecked(detector.value in enabled)

    def _synchronize_new_scan_panel(self) -> None:
        """Replay passive CT400 state when a scan view is opened later."""
        panel = self._control_panel
        if panel is None:
            return
        if self.ct400_device is not None:
            simulated = self._ct400_is_configured_simulation() and isinstance(self.ct400_device, DummyCT400)
            panel.set_instrument(self.ct400_device, simulated=simulated)
            if simulated:
                panel.on_instrument_connected(True)
        panel.set_connected_laser_input(
            self._ct400_connected_laser_input,
            configured_speed_nm_s=self._ct400_connected_speed_nm_s,
        )
        panel.set_ct400_operation_state(self._ct400_operation_state.name)

    def _connect_scan_signals(self) -> None:
        """Connect scan signals only once, after deferred widget construction."""
        plot, panel = self._plot_widget, self._control_panel
        if plot is None or panel is None:
            return
        plot.open_scan_requested.connect(self._open_scan_file)
        plot.add_scan_requested.connect(self._add_scan_to_plot)
        plot.scan_export_idle.connect(self._resume_close_after_scan_export)
        panel.set_lease_start_authorizer(self._ct400_lease_available_for_new_operation)
        panel.scan_data_ready.connect(self._handle_scan_data)
        panel.operation_started.connect(self._handle_ct400_scan_started)
        panel.operation_finished.connect(self._handle_ct400_scan_finished)
        panel.scan_safety_uncertain.connect(self._handle_ct400_scan_safety_uncertain)
        panel.scan_warning.connect(lambda message: self.statusBar().showMessage(message, 10000))

    def _set_scan_connected_laser_input(self, laser_input: LaserInput | None, **kwargs) -> None:
        if self._control_panel is not None:
            self._control_panel.set_connected_laser_input(laser_input, **kwargs)

