    def _update_ct400_visuals(self, state: CT400Status, message: str | None = None):
        """Updates all UI elements related to the CT400 connection status.

        This centralizes the logic for updating the menu action, status bar label,
        and main status message based on the device's state.

        Args:
            state: The new CT400Status to reflect in the UI.
            message: An optional message to display in the status bar.
        """
        action = getattr(self, "ct400_connect_action", None)
        label = getattr(self, "ct400_status_label", None)
        if not action or not label:
            return

        action_enabled, action_checked = True, False
        status_property = state.name.lower()

        state_map = {
            CT400Status.CONNECTED: ("Disconnect CT400", ":/icons/disconnect.svg", True, True),
            CT400Status.DISCONNECTED: ("Connect CT400", ":/icons/connect.svg", True, False),
            CT400Status.CONNECTING: ("Connecting...", ":/icons/spinner.svg", False, True),
            CT400Status.DISCONNECTING: ("Disconnecting...", ":/icons/spinner.svg", False, False),
            CT400Status.ERROR: ("Connect CT400 (Error)", ":/icons/connect.svg", True, False),
            CT400Status.DISCONNECT_UNCONFIRMED: ("Disconnect CT400 (Retry)", ":/icons/disconnect.svg", True, True),
            CT400Status.SCAN_STATE_UNCERTAIN: ("Disconnect CT400 (Recovery)", ":/icons/disconnect.svg", True, True),
            CT400Status.RECOVERY_CONFIRMATION_REQUIRED: ("Confirm CT400 Safe State", ":/icons/check.svg", True, False),
            CT400Status.UNAVAILABLE: ("CT400 Unavailable", ":/icons/laser.svg", False, False),
            CT400Status.UNKNOWN: ("CT400 Initializing", ":/icons/spinner.svg", False, False),
        }

        text, icon, action_enabled, action_checked = state_map[state]
        action.setText(text)
        action.setIcon(QIcon(icon))
        self._ct400_visual_state = state
        action.setEnabled(
            action_enabled
            and isinstance(self.ct400_device, CT400)
            and self._ct400_operation_state is CT400OperationState.IDLE
            and (state is not CT400Status.DISCONNECT_UNCONFIRMED or self._ct400_cleanup_laser_input is not None)
            and (
                state is not CT400Status.SCAN_STATE_UNCERTAIN
                or (self._ct400_cleanup_laser_input is not None and self._ct400_recovery_input_matches)
            )
            and (
                state is not CT400Status.RECOVERY_CONFIRMATION_REQUIRED
                or (self._ct400_cleanup_laser_input is not None and self._ct400_recovery_input_matches)
            )
        )
        action.setChecked(action_checked)

        label.setText(f"CT400: {state.name.replace('_', ' ').title()}")
        label.setProperty(PROP_STATUS, status_property)
        label.style().unpolish(label)
        label.style().polish(label)

        self._render_status_label(
            label,
            format_ct400_status(
                state,
                simulated=isinstance(self.ct400_device, DummyCT400),
                operation=self._ct400_operation_state,
            ),
        )

        if message:
            timeout = 5000 if state in [CT400Status.CONNECTED, CT400Status.DISCONNECTED, CT400Status.ERROR] else 0
            self.statusBar().showMessage(message, timeout)

        alignment_panel = getattr(self, "alignment_tab", None)
        if alignment_panel is not None:
            alignment_panel._update_control_availability()

        if state == CT400Status.ERROR:
            self._ct400_error_reset_timer.start(3000)
        elif self._ct400_error_reset_timer.isActive():
            self._ct400_error_reset_timer.stop()

        self.is_ct400_connected_state = state == CT400Status.CONNECTED
        self._refresh_global_status()

    @staticmethod
    def _render_status_label(label: QLabel, status) -> None:
        if (
            label.text() == status.text
            and label.toolTip() == status.tooltip
            and label.property(PROP_STATUS) == status.state
        ):
            return
        label.setText(status.text)
        label.setToolTip(status.tooltip)
        label.setAccessibleName(status.text)
        label.setProperty(PROP_STATUS, status.state)
        label.style().unpolish(label)
        label.style().polish(label)

    def _refresh_global_status(self) -> None:
        """Render compact status from existing lifecycle owners without device reads."""
        if not hasattr(self, "cameras_status_label"):
            return
        self._render_status_label(
            self.ct400_status_label,
            format_ct400_status(
                getattr(self, "_ct400_visual_state", CT400Status.UNKNOWN),
                simulated=isinstance(self.ct400_device, DummyCT400),
                operation=self._ct400_operation_state,
            ),
        )
        camera_states = []
        for identifier, config in self.config.cameras.items():
            if not config.enabled:
                continue
            if not identifier or identifier.startswith("PUT_"):
                camera_states.append(CameraStatus.UNAVAILABLE)
                continue
            panel = self.camera_panels.get(identifier)
            if panel is None:
                camera_states.append(CameraStatus.INITIALIZING)
            elif panel._recovery_active or identifier in self._camera_recovery_tasks:
                camera_states.append(CameraStatus.RECOVERING)
            elif panel.camera is None or panel._camera_error_active or panel._recovery_failed:
                camera_states.append(CameraStatus.UNAVAILABLE)
            elif config.backend == "simulation":
                camera_states.append(CameraStatus.SIMULATED)
            elif panel.camera.is_streaming:
                camera_states.append(CameraStatus.STREAMING)
            else:
                camera_states.append(CameraStatus.UNAVAILABLE)
        self._render_status_label(self.cameras_status_label, format_cameras_status(camera_states))
        self._render_status_label(
            self.matlab_status_label, format_matlab_status(self.plot_widget.matlab_engine_manager.state)
        )
        self._render_status_label(self.activity_status_label, format_activity_status(self._ct400_operation_state))

    @Slot()
    def _reset_ct400_error_visuals(self):
        """Return an error status to disconnected while owned by this window."""
        state = (
            CT400Status.SCAN_STATE_UNCERTAIN
            if self._ct400_scan_state_uncertain
            else CT400Status.DISCONNECT_UNCONFIRMED
            if self._ct400_device_has_unresolved_laser_state()
            else CT400Status.DISCONNECTED
        )
        message = (
            "Scan state is uncertain. Use operator-controlled recovery."
            if state is CT400Status.SCAN_STATE_UNCERTAIN
            else "Error occurred. Ready to retry disconnect."
            if state is CT400Status.DISCONNECT_UNCONFIRMED
            else "Error occurred. Ready to connect."
        )
        self._update_ct400_visuals(state, message)

