    @Slot(dict)
    def handle_power_data(self, power_data: dict):
        logger.debug(f"Received power data: {power_data}")
        if self.histogram_widget and hasattr(self.histogram_widget, "schedule_update"):
            try:
                self.histogram_widget.schedule_update(power_data)
            except Exception:
                logger.exception("Error updating histogram widget")
        else:
            logger.warning("Histogram widget not available or does not have schedule_update method.")

    @Slot(object)
    def _handle_power_monitor_recording_started(self, settings: PowerMonitorAcquisitionSettings) -> None:
        try:
            trace_widget = self.power_monitor_trace_widget
            if trace_widget is None:
                trace_widget = PowerMonitorTraceWidget(settings=self.settings, parent=self.histogram_plot_container)
                trace_widget.export_idle.connect(
                    self._resume_close_after_power_monitor_export, Qt.ConnectionType.QueuedConnection
                )
                self.histogram_plot_layout.addWidget(trace_widget, stretch=1)
                self.power_monitor_trace_widget = trace_widget
            trace_widget.start_recording(settings)
            trace_widget.show()
        except Exception:
            logger.exception("Error starting Power Monitor recording trace")

    @Slot(object)
    def _handle_power_monitor_recording_sample(self, sample: PowerMonitorRecordingSample) -> None:
        trace_widget = self.power_monitor_trace_widget
        if trace_widget is None:
            return
        try:
            trace_widget.append_sample(sample)
        except Exception:
            logger.exception("Error updating Power Monitor recording trace")

    @Slot(object)
    def _handle_power_monitor_recording_completed(self, recording: PowerMonitorRecording) -> None:
        trace_widget = self.power_monitor_trace_widget
        if trace_widget is None:
            return
        try:
            trace_widget.set_completed_recording(recording)
            if not trace_widget._user_hidden:
                trace_widget.show()
        except Exception:
            logger.exception("Error finalizing Power Monitor recording trace")

    @Slot()
    def _handle_power_monitor_recording_discarded(self) -> None:
        trace_widget = self.power_monitor_trace_widget
        if trace_widget is None:
            return
        try:
            trace_widget.discard_recording()
        except Exception:
            logger.exception("Error clearing discarded Power Monitor recording trace")

    def _cleanup_cameras(self):
        if self._camera_cleanup_complete:
            return
        if not self._camera_cleanup_requested:
            self._camera_cleanup_requested = True
            logger.info("Closing %d camera(s)...", len(self.cameras))
            panels = list(
                dict.fromkeys([*self.camera_panels.values(), *self.camera_container.findChildren(CameraPanel)])
            )
            self._camera_shutdown_panels = panels
            for panel in panels:
                panel.conversion_shutdown_complete.connect(self._schedule_camera_retirement)
                panel.prepare_camera_shutdown()
            # Every producer stops before any converter is asked to retire.
            for camera in self.cameras:
                try:
                    camera.close()
                except Exception:
                    logger.exception("Error closing camera %s", camera.camera_name)
            for panel in panels:
                panel._teardown_conversion_pipeline()

        if any(not panel._conversion_shutdown_complete for panel in self._camera_shutdown_panels):
            return

        # No live converter remains. Only now may panel/native owners go away.
        layout = self.camera_container.layout()
        if layout is not None:
            while layout.count():
                item = layout.takeAt(0)
                if item is None:
                    break
                widget = item.widget()
                if widget is not None and not isinstance(widget, CameraPanel):
                    widget.close()
                    widget.deleteLater()
        for panel in self._camera_shutdown_panels:
            panel.close()
            panel.deleteLater()
        self._camera_shutdown_panels.clear()
        self.cameras.clear()
        self.camera_panels.clear()
        self._camera_cleanup_complete = True
        logger.info("Camera cleanup finished.")

    @Slot()
    def _schedule_camera_retirement(self):
        QTimer.singleShot(0, self, self._finish_camera_retirement)

    @Slot()
    def _finish_camera_retirement(self):
        if not self._camera_cleanup_complete:
            self._cleanup_cameras()
        if self._camera_cleanup_complete:
            self._resume_close_after_monitor_retirement()

    def _disable_configured_ct400_input_for_shutdown(self) -> bool:
        """Apply the connection-level selected-input cleanup before close."""
        laser_input = self._ct400_cleanup_laser_input
        if laser_input is None:
            if self._ct400_device_has_unresolved_laser_state():
                QMessageBox.warning(
                    self,
                    "CT400 State Uncertain",
                    "The configured laser input is unknown. Follow the approved laboratory safe-state "
                    "procedure before disconnecting or closing the instrument.",
                )
                return False
            return True
        try:
            if self.ct400_device is None:
                raise RuntimeError("CT400 unavailable during configured-input shutdown")
            self.ct400_device.cmd_laser(
                laser_input=laser_input,
                enable=Enable.DISABLE,
                wavelength=self.config.scan_defaults.safe_parking_wavelength,
                power=self.config.scan_defaults.laser_power,
            )
            logger.info("Shutdown disabled configured CT400 input %s.", laser_input.name)
            return True
        except Exception as exc:
            logger.exception(
                "Shutdown laser disable could not be confirmed for configured input %s",
                laser_input.name,
            )
            QMessageBox.warning(
                self,
                "Laser Disable Not Confirmed",
                f"Laser disable could not be confirmed for configured input {laser_input.name}.\n\n"
                "The application will continue resource cleanup. CT400 native resource close is a separate "
                "operation.\n\n"
                f"{exc}",
            )
            return False

    @override
    def closeEvent(self, event: QtGui.QCloseEvent):
        """
        Handles the user closing the window. Ensures all hardware and threads
        are shut down gracefully. This is the single source of truth for cleanup.
        """
        self._shutdown_requested = True
        self._lazy_init_timer.stop()
        if self._shutdown_complete:
            event.accept()
            return
        plot = self._plot_widget
        if plot is not None:
            plot.prepare_shutdown()
        else:
            # A window that never opened Wavelength Scan still owns MATLAB.
            self.matlab_engine_manager.shutdown()
        # A paused/checkpoint campaign still owns the scan panel even if no scan
        # thread exists. Defer all native cleanup until its final record is
        # committed and the CT400 reservation is released.
        campaign_dialog = getattr(self, "_ct400_campaign_dialog", None)
        if campaign_dialog is not None and campaign_dialog.active:
            event.ignore()
            self.statusBar().showMessage("Stopping CT400 ETA campaign and saving its final record…", 0)
            campaign_dialog.request_shutdown()
            return

        close_started_at = time.perf_counter()
        logger.info("Application close requested. Initiating shutdown sequence...")
        if self._defer_close_for_active_work(event):
            return

        self.statusBar().showMessage("Shutting down...", 0)

        # UI preferences must be saved before camera panels are removed.
        if not getattr(self, "_shutdown_panels_requested", False):
            self._shutdown_panels_requested = True
            self._save_ui_preferences()
            self.histogram_control.shutdown_complete.connect(self._resume_close_after_monitor_retirement)
            if plot is not None:
                plot.shutdown_complete.connect(self._resume_close_after_monitor_retirement)
            self._cleanup_shutdown_panel_workers()
        if not self.histogram_control.shutdown_finished:
            event.ignore()
            self.statusBar().showMessage("Waiting for power monitor worker retirement…", 0)
            return
        scan_retired = plot.shutdown_finished if plot is not None else self.matlab_engine_manager.shutdown_finished
        if not scan_retired:
            event.ignore()
            if self.matlab_engine_manager.state is MatlabEngineState.SHUTDOWN_FAILED:
                self.statusBar().showMessage("MATLAB shutdown failed; native ownership is retained.", 0)
            else:
                self.statusBar().showMessage("Waiting for MATLAB export/startup and Engine cleanup…", 0)
            return
        self._cleanup_cameras()
        if not self._camera_cleanup_complete:
            event.ignore()
            self.statusBar().showMessage("Waiting for camera conversion to finish…", 0)
            return
        self._disconnect_piezos_for_shutdown()
        self._release_ct400_for_shutdown()
        self._cleanup_vimbasystem()

        logger.info("Shutdown complete.")
        self._finish_shutdown_ui()
        self._shutdown_complete = True
        event.accept()
        self.shutdown_complete.emit()
        logger.info("MainWindow.closeEvent cleanup returned after %.2f s.", time.perf_counter() - close_started_at)

    def _defer_close_for_active_work(self, event: QtGui.QCloseEvent) -> bool:
        """Defer native cleanup until owners and active tasks finish, in original priority."""
        shg = getattr(self, "_shg_tab", None)
        if shg is not None and shg.active:
            event.ignore()
            self.statusBar().showMessage("Cancelling synchronized simulation; waiting for both owner cleanups…", 0)
            shg.request_shutdown()
            return True
        edfa_panel = getattr(self, "_edfa_panel", None)
        if edfa_panel is not None and not edfa_panel.shutdown_finished:
            event.ignore()
            self._pending_edfa_close = True
            self.statusBar().showMessage("Releasing EDFA session before application shutdown…", 0)
            edfa_panel.request_shutdown()
            return True
        pm5020_panel = getattr(self, "_pm5020_panel", None)
        if pm5020_panel is not None and not pm5020_panel.shutdown_finished:
            event.ignore()
            self._pending_pm5020_close = True
            self.statusBar().showMessage("Closing PM5020 safely before application shutdown…", 0)
            pm5020_panel.request_shutdown()
            return True
        scan_panel = self._control_panel
        scan_thread = getattr(scan_panel, "scan_thread", None)
        try:
            scan_active = scan_thread is not None and scan_thread.isRunning()
        except RuntimeError:
            scan_active = False
        if scan_active and scan_thread is not None and scan_panel is not None:
            event.ignore()
            self.statusBar().showMessage("Stopping/waiting for CT400 scan to finish…", 0)
            logger.info("Deferring application close until the active CT400 scan worker finishes.")
            self._pending_scan_close = True
            if not getattr(self, "_close_resume_connected", False):
                self._close_resume_connected = True
                scan_thread.finished.connect(self._resume_close_after_scan)
            scan_panel._stop_scan(cancelled=True)
            if not scan_thread.isRunning():
                self._resume_close_after_scan()
            return True

        if self._scan_import_task is not None:
            event.ignore()
            self._pending_scan_import_close = True
            self._update_scan_import_actions()
            self.statusBar().showMessage("Waiting for the scan file reader to finish before closing…", 0)
            return True

        if self._plot_widget is not None and self._plot_widget.scan_export_busy:
            event.ignore()
            self._pending_scan_export_close = True
            self._plot_widget.request_scan_export_close()
            self.statusBar().showMessage("Waiting for scan data file writing to complete before closing…", 0)
            return True

        trace = self.power_monitor_trace_widget
        if trace is not None and trace.power_monitor_export_busy:
            event.ignore()
            self._pending_power_monitor_export_close = True
            trace.request_power_monitor_export_close()
            self.statusBar().showMessage("Waiting for Power Monitor file writing to finish…", 0)
            return True

        if self._camera_lifecycle_busy():
            event.ignore()
            self._pending_camera_lifecycle_close = True
            self.statusBar().showMessage("Waiting for camera operation to finish…", 0)
            logger.info("Deferring application close until camera recovery/auto operations finish.")
            return True

        if self._ct400_operation_state in (CT400OperationState.CONNECTING, CT400OperationState.DISCONNECTING):
            event.ignore()
            self._pending_ct400_operation_close = True
            self.statusBar().showMessage("Waiting for CT400 connection operation to finish…", 0)
            logger.info("Deferring application close until the CT400 Connect/Disconnect operation finishes.")
            return True

        if self._ct400_operation_state is CT400OperationState.MONITORING:
            event.ignore()
            self._pending_ct400_operation_close = True
            self.statusBar().showMessage("Stopping power monitoring before CT400 shutdown…", 0)
            self.histogram_control._stop_monitoring()
            return True

        if self._ct400_operation_state is CT400OperationState.ALIGNMENT:
            event.ignore()
            self._pending_ct400_operation_close = True
            self.statusBar().showMessage("Stopping/waiting for alignment CT400 cleanup…", 0)
            logger.info("Deferring application close until alignment laser cleanup completes.")
            self.alignment_tab.request_stop()
            return True

        if self._init_tasks:
            event.ignore()
            self._pending_init_close = True
            self.statusBar().showMessage("Waiting for hardware initialization to finish…", 0)
            logger.info("Deferring application close with %d initialization task(s) active.", len(self._init_tasks))
            for task in tuple(self._init_tasks):
                cancel = getattr(task.worker, "cancel", None)
                if callable(cancel):
                    cancel()
            return True

        if self._piezo_operations_in_flight:
            event.ignore()
            self._pending_piezo_operation_close = True
            active_sides = ", ".join(sorted(self._piezo_operations_in_flight))
            self.statusBar().showMessage("Waiting for piezo operation to finish…", 0)
            logger.info("Deferring application close while piezo operation(s) remain active: %s", active_sides)
            return True

        return False

    @Slot()
    def _resume_close_after_monitor_retirement(self):
        if self._shutdown_requested and not self._shutdown_complete:
            QTimer.singleShot(0, self, self.close)

    @Slot(str)
    def _report_matlab_shutdown_failure(self, error: str):
        self.statusBar().showMessage(f"MATLAB shutdown failed: {error}. Native ownership is retained.", 0)

    def _cleanup_shutdown_panel_workers(self) -> None:
        """Release panel worker resources before stopping cameras."""
        if self._alignment_tab:
            self.alignment_tab.cleanup()

        if hasattr(self, "histogram_control") and self.histogram_control:
            self.histogram_control.cleanup_worker_thread()

        if self._plot_widget is not None:
            self._plot_widget.cleanup()

    def _disconnect_piezos_for_shutdown(self) -> None:
        """Best-effort piezo cleanup with independent failure boundaries."""
        for side, piezo in (("left", self.piezo_left), ("right", self.piezo_right)):
            try:
                if piezo and piezo.is_connected():
                    piezo.disconnect()
            except Exception:
                logger.exception("Error disconnecting %s piezo hardware during shutdown", side)

    def _release_ct400_for_shutdown(self) -> None:
        """Retain the CT400 input safe-state and native handle close ordering."""
        # Stop monitoring above so its own selected input is handled before
        # releasing the CT400. A successful GUI disconnect already disabled
        # the configured input. Retain that knowledge separately from the UI
        # connection flag so an error-state disconnect is retried at shutdown.
        device = self.ct400_device
        if isinstance(device, CT400):
            if self.is_ct400_connected_state or self._ct400_connection_configured:
                self._disable_configured_ct400_input_for_shutdown()
            if device.handle is not None:
                logger.info("MainWindow.closeEvent: Releasing initialized CT400 resources.")
                try:
                    device.close()
                except Exception as exc:
                    logger.exception("CT400 native resource close failed")
                    QMessageBox.warning(
                        self,
                        "CT400 Resource Close Failed",
                        f"CT400 native resource close failed:\n\n{exc}",
                    )
        elif isinstance(device, DummyCT400) and self.is_ct400_connected_state:
            # Retain the existing simulation close path; never treat the dummy
            # as a native handle owner or send configured physical commands.
            logger.info("MainWindow.closeEvent: Closing connected DummyCT400 simulation.")
            device.close()

    def _finish_shutdown_ui(self) -> None:
        """Finalize UI resources only after hardware cleanup."""
        self._pending_init_close = False
        self._pending_camera_lifecycle_close = False
        self._pending_piezo_operation_close = False
        try:
            self.matlab_engine_manager.state_changed.disconnect(self._refresh_global_status)
        except (AttributeError, RuntimeError, TypeError):
            pass
        self.log_console.stop_updates()
        self.log_console_dock.hide()

    def _save_ui_preferences(self) -> None:
        """Save only presentation state and the selected scan detector IDs."""
        if not self.isFullScreen():
            self.settings.set_geometry(self.saveGeometry())
        if self.control_container.isVisible():
            self.settings.set_splitter_sizes(self.main_splitter.sizes())
        # Selected tab intentionally not persisted: next launch opens Power Monitor.
        self.settings.set_log_console_visible(self.log_console_dock.isVisible())
        self.settings.set_log_console_state(self.saveState())
        self.settings.set_log_console_layout_version(2)
        if self.log_console_dock.isFloating():
            self.settings.set_log_console_geometry(self.log_console_dock.saveGeometry())
        self.settings.set_log_console_level(self.log_console.level_filter.currentText())
        if self._control_panel is not None:
            self.settings.set_scan_detectors([detector.value for detector in self._control_panel._selected_scan_detectors()])
        pm5020_panel = getattr(self, "_pm5020_panel", None)
        if pm5020_panel is not None:
            pm5020_panel.save_preferences(self.settings)
        for camera_id, panel in self.camera_panels.items():
            self.settings.set_camera_controls_visible(camera_id, panel.get_controls_visible())
        self.settings.sync()

