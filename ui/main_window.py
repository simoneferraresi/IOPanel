    def _import_scan(self, *, add_overlay: bool) -> None:
        """Shared schema-v2 file selection, validation, and parsing path."""
        mode = "Add Scan to Plot" if add_overlay else "Open Scan"
        if self._scan_import_shutdown_in_progress():
            return
        if self._scan_import_task is not None:
            self.statusBar().showMessage("A saved scan is already loading.", 5000)
            return
        if self._scan_import_is_blocked():
            self.statusBar().showMessage("Wait for the CT400 scan to finish before importing a saved scan.", 5000)
            return
        filename, _selected_filter = QFileDialog.getOpenFileName(
            self,
            mode,
            str(self.settings.directory("Paths/scan_import")),
            "IOPanel CSV (*.csv);;IOPanel MATLAB Data (*.mat)",
        )
        if not filename:
            return
        if self._scan_import_shutdown_in_progress() or self._scan_import_task is not None:
            return
        if self._scan_import_is_blocked():
            self.statusBar().showMessage(
                "The CT400 scan started while the file dialog was open; import cancelled.", 5000
            )
            return
        # Keep every dialog and plot operation on the GUI thread. Only the
        # validated schema-v2 file parse runs on a worker-owned QThread.
        self._scan_import_context = (
            add_overlay,
            mode,
            filename,
            self.plot_widget.current_measurement,
            self._scan_import_generation,
        )
        self._scan_import_outcome = None
        self._scan_import_thread_stopped = False
        worker = ScanImportWorker(filename, loader=load_scan)
        task = TaskRunner(worker)
        # Keep the native QThread owned by this GUI object until Qt processes
        # its deferred deleteLater, even after the Python TaskRunner reference
        # is cleared on the queued thread-finished notification.
        task.worker_thread.setParent(self)
        task_id = id(task)
        self._owned_scan_import_tasks[task_id] = task
        task.worker_thread.destroyed.connect(
            lambda _obj=None, key=task_id: self._owned_scan_import_tasks.pop(key, None)
        )
        self._scan_import_task = task
        worker.outcome.connect(self._on_scan_import_parsed, Qt.ConnectionType.QueuedConnection)
        task.worker_thread.finished.connect(self._on_scan_import_thread_finished, Qt.ConnectionType.QueuedConnection)
        self._update_scan_import_actions()
        self.statusBar().showMessage(f"Reading {filename}…", 0)
        task.start()

    @Slot(object)
    def _on_scan_import_parsed(self, outcome: ScanImportOutcome) -> None:
        self._scan_import_outcome = outcome
        self._complete_scan_import_if_ready()

    @Slot()
    def _on_scan_import_thread_finished(self) -> None:
        self._scan_import_thread_stopped = True
        self._complete_scan_import_if_ready()

    def _complete_scan_import_if_ready(self) -> None:
        # Qt does not promise queued outcome/thread-finished delivery order.
        if self._scan_import_task is None or not self._scan_import_thread_stopped:
            return
        outcome = self._scan_import_outcome
        if outcome is None:
            return
        context = self._scan_import_context
        self._scan_import_task = None
        self._scan_import_context = None
        self._scan_import_outcome = None
        self._scan_import_thread_stopped = False
        self._update_scan_import_actions()
        if self._pending_scan_import_close:
            self._pending_scan_import_close = False
            QTimer.singleShot(0, self, self.close)
            return
        if context is None or self._scan_import_shutdown_in_progress():
            return
        add_overlay, mode, filename, original_measurement, original_generation = context
        if (
            self._scan_import_is_blocked()
            or original_generation != self._scan_import_generation
            or self.plot_widget.current_measurement is not original_measurement
        ):
            self.statusBar().showMessage("A scan changed while the file was loading; import cancelled.", 5000)
            return
        if outcome.error is not None:
            if outcome.unexpected:
                logger.error("Unexpected scan import failure for %s: %s", filename, outcome.error)
                QMessageBox.warning(self, f"Could Not {mode}", f"The scan could not be read: {outcome.error}")
            else:
                logger.warning("Rejected imported scan %s: %s", filename, outcome.error)
                QMessageBox.warning(self, f"Could Not {mode}", outcome.error)
            return
        scan = outcome.scan
        if scan is None:
            logger.error("Scan parser returned no result for %s", filename)
            QMessageBox.warning(self, f"Could Not {mode}", "The scan parser returned no result.")
            return
        self._apply_imported_scan(scan, add_overlay=add_overlay)

    def _apply_imported_scan(self, scan, *, add_overlay: bool) -> None:
        """Complete parsed imports exclusively on the Qt GUI thread."""
        if add_overlay:
            if not self.plot_widget.add_imported_overlay(scan):
                self.statusBar().showMessage("Overlay already present or the overlay limit was reached.", 5000)
                return
            self.settings.set_directory("Paths/scan_import", scan.source_path.parent)
            self.statusBar().showMessage(f"Added overlay {scan.source_path.name}", 5000)
            return
        while self.plot_widget.has_unsaved_acquisition():
            existing_measurement = self.plot_widget.current_measurement
            answer = QMessageBox.question(
                self,
                "Replace Unsaved Scan?",
                "The current acquired scan has not been successfully saved. Replace it with this imported scan?",
                QMessageBox.StandardButton.Yes | QMessageBox.StandardButton.No,
                QMessageBox.StandardButton.No,
            )
            if answer != QMessageBox.StandardButton.Yes:
                return
            if self._scan_import_is_blocked():
                self.statusBar().showMessage("The CT400 scan started during confirmation; import cancelled.", 5000)
                return
            if self.plot_widget.current_measurement is not existing_measurement:
                continue
            break
        if self._scan_import_is_blocked():
            self.statusBar().showMessage("The CT400 scan is still completing; import cancelled.", 5000)
            return
        if self._scan_import_shutdown_in_progress():
            return
        if not self.plot_widget.set_imported_scan(scan):
            QMessageBox.warning(self, "Could Not Plot Scan", "The scan was read but its traces could not be plotted.")
            return
        self.settings.set_directory("Paths/scan_import", scan.source_path.parent)
        self.statusBar().showMessage(f"Imported {scan.source_path.name}", 5000)

    def _scan_import_is_blocked(self) -> bool:
        """Keep imports blocked until the scan worker lifecycle has fully unwound."""
        panel = self._control_panel
        return (
            getattr(self, "_ct400_operation_state", None) is CT400OperationState.SCANNING
            or bool(getattr(panel, "scanning", False))
            or getattr(panel, "scan_thread", None) is not None
        )

    def _update_scan_import_actions(self) -> None:
        enabled = (
            self._scan_import_task is None
            and not self._scan_import_is_blocked()
            and not self._scan_import_shutdown_in_progress()
        )
        action = getattr(self, "open_scan_action", None)
        if action is not None:
            action.setEnabled(enabled)
        action = getattr(self, "add_scan_action", None)
        if action is not None:
            action.setEnabled(enabled)
        plot_widget = self._plot_widget
        if plot_widget is not None and hasattr(plot_widget, "load_btn"):
            plot_widget.load_btn.setEnabled(enabled)

    def _scan_import_shutdown_in_progress(self) -> bool:
        return any(
            bool(getattr(self, name, False))
            for name in (
                "_pending_scan_close",
                "_pending_scan_import_close",
                "_pending_scan_export_close",
                "_pending_init_close",
                "_pending_camera_lifecycle_close",
                "_pending_ct400_operation_close",
                "_pending_piezo_operation_close",
                "_camera_cleanup_complete",
            )
        )

    @Slot()
    def _on_refresh_instruments_triggered(self):
        """
        Manually triggers discovery for Piezos and CT400.
        Useful if instruments were turned on after the GUI started.
        """
        logger.info("Manual Instrument Refresh requested.")
        if self._shutdown_requested or self._pending_init_close:
            logger.info("Ignoring instrument refresh while application close is pending.")
            return
        if self._pending_piezo_operation_close:
            logger.info("Ignoring instrument refresh while piezo operation shutdown is pending.")
            return
        if self._alignment_hardware_transition_blocked():
            self.statusBar().showMessage("Stop alignment before refreshing instruments.", 5000)
            return
        self.statusBar().showMessage("Scanning for instruments...", 3000)

        # 1. Refresh Piezos
        # We always try to find piezos if requested, unless a scan is already running.
        piezo_task = self.piezo_task
        if self._piezo_operations_in_flight:
            logger.info("Skipping piezo discovery while a piezo connection operation is active.")
        elif piezo_task is not None and piezo_task.worker_thread.isRunning():
            logger.info("Piezo discovery already running. Skipping.")
        else:
            self._init_piezos_lazy()

        # 2. Refresh CT400
        # Only try to re-initialize CT400 if we are currently using a Dummy device
        # or if no device is set. We don't want to kill a live connection.
        is_dummy = isinstance(self.ct400_device, DummyCT400)
        is_none = self.ct400_device is None

        if is_dummy or is_none:
            ct400_task = self.ct400_task
            if ct400_task is not None and ct400_task.worker_thread.isRunning():
                logger.info("CT400 init already running. Skipping.")
            else:
                logger.info("Current CT400 is Dummy/None. Re-scanning for real hardware...")
                self._update_ct400_visuals(state=CT400Status.UNKNOWN, message="Searching for CT400...")

                self._init_ct400_lazy()
        else:
            logger.info("CT400 is already connected to real hardware. Skipping refresh.")
            self.statusBar().showMessage("CT400 connected. Scanning Piezos only...", 3000)

