    def _restore_ui_preferences(self) -> None:
        """Apply stored presentation preferences after all UI widgets exist."""
        saved_geometry = self.settings.geometry()
        if saved_geometry is not None:
            self.restoreGeometry(saved_geometry)
        saved_sizes = self.settings.splitter_sizes(self.main_splitter.count())
        if saved_sizes is not None:
            self.main_splitter.setSizes(saved_sizes)
        self.tab_widget.setCurrentIndex(
            self.settings.active_tab(self.tab_widget.count(), self.tab_widget.currentIndex())
        )
        saved_detectors = set(self.settings.scan_detectors())
        for detector, checkbox in self.control_panel.scan_detector_cbs.items():
            checkbox.setChecked(detector.value in saved_detectors)

    def _restore_log_console_preferences(self) -> None:
        layout_version = self.settings.log_console_layout_version()
        if layout_version != 2:
            # Version 1 stored a bottom-docked state. Give existing users the
            # floating-first layout once, while retaining their visibility.
            self.log_console_dock.setFloating(True)
            self._place_log_console_on_primary_screen()
        else:
            state = self.settings.log_console_state()
            if state is not None:
                self.restoreState(state)
            if self.log_console_dock.isFloating():
                geometry = self.settings.log_console_geometry()
                if geometry is None or not self.log_console_dock.restoreGeometry(geometry):
                    self._place_log_console_on_primary_screen()
                else:
                    self._keep_log_console_on_available_screen()
        self.log_console.level_filter.setCurrentText(self.settings.log_console_level())
        console_visible = self.settings.log_console_visible(False)
        self.log_console_dock.setVisible(console_visible)
        self.log_console_action.setChecked(console_visible)

    def _place_log_console_on_primary_screen(self) -> None:
        screen = QApplication.primaryScreen()
        if screen is None:
            self.log_console_dock.resize(900, 380)
            return
        available = screen.availableGeometry()
        width = min(920, max(1, available.width() - 32))
        height = min(380, max(1, available.height() - 64))
        self.log_console_dock.resize(width, height)
        self.log_console_dock.move(
            available.x() + max(0, (available.width() - width) // 2),
            available.y() + max(0, (available.height() - height) // 2),
        )

    def _keep_log_console_on_available_screen(self) -> None:
        frame = self.log_console_dock.frameGeometry()
        screens = QApplication.screens()
        intersecting = [screen for screen in screens if screen.availableGeometry().intersects(frame)]
        if not intersecting:
            self._place_log_console_on_primary_screen()
            return
        screen = max(
            intersecting,
            key=lambda candidate: (
                candidate.availableGeometry().intersected(frame).width()
                * candidate.availableGeometry().intersected(frame).height()
            ),
        )
        available = screen.availableGeometry()
        width = min(frame.width(), available.width())
        height = min(frame.height(), available.height())
        x = min(max(frame.x(), available.left()), available.right() - width + 1)
        y = min(max(frame.y(), available.top()), available.bottom() - height + 1)
        self.log_console_dock.resize(width, height)
        self.log_console_dock.move(x, y)

    piezo_connection_succeeded = Signal(str)
    piezo_connection_failed = Signal(str, str)

    @Slot(str)
    def connect_piezo(self, side: str):
        """Connects or disconnects a piezo controller on a worker thread."""
        if self._pending_piezo_operation_close:
            logger.info("Ignoring %s piezo operation while application close is pending.", side)
            return
        if side not in {"left", "right"} or side in self._piezo_operations_in_flight:
            return
        if self._alignment_hardware_transition_blocked():
            logger.info("Ignoring %s piezo operation while alignment owns the hardware.", side)
            return
        if side == "left":
            piezo = self.piezo_left
            port = self.config.instruments.piezo_left_serial
        else:
            piezo = self.piezo_right
            port = self.config.instruments.piezo_right_serial

        if not piezo:
            logger.error(f"Cannot connect {side} piezo: object is None.")
            return

        do_connect = not piezo.is_connected()

        worker = PiezoConnectionWorker(piezo, side, port, do_connect)

        # Connect signals to the main thread's *slots*
        worker.signals.connection_succeeded.connect(self.piezo_connection_succeeded)
        worker.signals.disconnection_succeeded.connect(self._on_piezo_disconnection_success)
        worker.signals.connection_failed.connect(self.piezo_connection_failed)

        # Reserve the controller before dispatch so Refresh cannot replace it.
        self._piezo_operations_in_flight.add(side)
        self._update_piezo_action(side)
        if not do_connect:
            self._sync_alignment_hardware()

        QThreadPool.globalInstance().start(worker)

    def _update_piezo_action(self, side: str):
        """Render the action from the current controller and operation state."""
        action = self.piezo_connect_left_action if side == "left" else self.piezo_connect_right_action
        piezo = self.piezo_left if side == "left" else self.piezo_right
        title = side.capitalize()
        if side in self._piezo_operations_in_flight:
            action.setText(f"{'Disconnecting' if piezo and piezo.is_connected() else 'Connecting'} {title}...")
            action.setEnabled(False)
        elif piezo is None:
            action.setText(f"{title} Piezo (Not Found)")
            action.setEnabled(False)
        else:
            connected = piezo.is_connected()
            action.setText(f"{'Disconnect' if connected else 'Connect'} {title} Piezo")
            action.setEnabled(True)

    def _alignment_hardware_transition_blocked(self) -> bool:
        panel = getattr(self, "alignment_tab", None)
        return bool(
            self._ct400_operation_state is CT400OperationState.ALIGNMENT
            or (panel is not None and (panel._active_mode is not None or panel._ct400_operation_state == "ALIGNMENT"))
        )

    def _sync_alignment_hardware(self):
        """Keep the alignment panel bound only to currently usable hardware."""
        panel = getattr(self, "alignment_tab", None)
        if panel is None:
            return
        panel.set_start_authorizer(self._is_alignment_operation_authorized)
        if self._alignment_hardware_transition_blocked():
            panel._update_control_availability()
            return
        ready = (
            self.ct400_device is not None
            and self.piezo_left is not None
            and self.piezo_right is not None
            and self.piezo_left.is_connected()
            and self.piezo_right.is_connected()
            and not self._piezo_operations_in_flight
            and not self._pending_piezo_operation_close
            and not self._alignment_hardware_transition_blocked()
        )
        if ready:
            panel.set_hardware(self.ct400_device, self.piezo_left, self.piezo_right)
        else:
            panel.clear_hardware()

    def _is_alignment_operation_authorized(self) -> bool:
        """Authorize alignment only for simulation or the explicitly connected physical input."""
        if self._ct400_operation_state is not CT400OperationState.IDLE:
            return False
        if self._ct400_scan_state_uncertain or self._ct400_recovery_disconnect_completed:
            return False
        device = self.ct400_device
        if isinstance(device, DummyCT400):
            return self.alignment_tab is not None and self.alignment_tab.ct400 is device
        if not isinstance(device, CT400) or self.alignment_tab is None or self.alignment_tab.ct400 is not device:
            return False
        captured_input = self._ct400_connected_laser_input
        if (
            not self._ct400_connection_configured
            or captured_input is None
            or captured_input is not self._ct400_cleanup_laser_input
        ):
            return False
        try:
            selected_input = LaserInput(self.alignment_tab.input_port_combo.currentData())
        except (TypeError, ValueError):
            return False
        return selected_input is captured_input

    @Slot(str)
    def _on_piezo_connection_success(self, side: str):
        logger.info(f"{side.capitalize()} Piezo connected successfully.")
        self._complete_piezo_operation(side)
        self.statusBar().showMessage(f"{side.capitalize()} Piezo connected.", 3000)

    @Slot(str)
    def _on_piezo_disconnection_success(self, side: str):
        logger.info(f"{side.capitalize()} Piezo disconnected.")
        self._complete_piezo_operation(side)
        self.statusBar().showMessage(f"{side.capitalize()} Piezo disconnected.", 3000)

    @Slot(str, str)
    def _on_piezo_connection_failed(self, side: str, error_message: str):
        logger.error(f"Failed to connect {side} piezo: {error_message}")
        self._complete_piezo_operation(side)
        QMessageBox.critical(self, f"{side.capitalize()} Piezo Error", f"Operation failed: {error_message}")

    def _complete_piezo_operation(self, side: str) -> bool:
        """Release one side's operation ownership and refresh dependent UI."""
        was_in_flight = side in self._piezo_operations_in_flight
        if was_in_flight:
            self._piezo_operations_in_flight.remove(side)
        self._update_piezo_action(side)
        if self._pending_piezo_operation_close:
            self.alignment_tab.clear_hardware()
            if was_in_flight:
                self._resume_close_after_piezo_operation()
        else:
            self._sync_alignment_hardware()
        return was_in_flight

    def _resume_close_after_piezo_operation(self):
        """Schedule close only after all piezo workers release their controllers."""
        if self._pending_piezo_operation_close and not self._piezo_operations_in_flight:
            QTimer.singleShot(0, self.close)

    @Slot(str, str)
    def _on_ct400_status_updated(self, state_name: str, message: str):
        """Updates the status bar from the CT400 init worker."""
        try:
            state = CT400Status[state_name.upper()]
        except KeyError:
            state = CT400Status.UNKNOWN

        self._update_ct400_visuals(state=state, message=message)

    @Slot(AbstractCT400)
    def _on_ct400_initialized(self, device: AbstractCT400):
        """
        Receives the initialized CT400 device (real or dummy) from the worker.
        This slot is now responsible for populating the rest of the UI
        that depends on the CT400.
        """
        logger.info(f"CT400 initialization finished. Received device: {type(device)}")
        if device is not self.ct400_device and self._ct400_operation_state in (
            CT400OperationState.CONNECTING,
            CT400OperationState.DISCONNECTING,
            CT400OperationState.SCANNING,
            CT400OperationState.MONITORING,
        ):
            logger.warning("Deferring CT400 replacement until the active operation releases its device.")
            self._defer_ct400_device_replacement(device)
            return
        if device is not self.ct400_device and self._ct400_device_has_unresolved_laser_state():
            self._defer_ct400_device_replacement(device)
            self._apply_pending_ct400_device_replacement()
            return
        if self._alignment_hardware_transition_blocked() and device is not self.ct400_device:
            logger.warning("Ignoring CT400 replacement while alignment owns the current hardware.")
            if isinstance(device, CT400):
                try:
                    device.close()
                except Exception:
                    logger.exception("Could not release rejected CT400 resources.")
            return
        old_device = self.ct400_device
        self.ct400_device = device
        if old_device is not device:
            self._ct400_connection_operation_token += 1
            self._ct400_connected_laser_input = None
            self._ct400_cleanup_laser_input = None
            self._ct400_connection_configured = False
            self._ct400_scan_state_uncertain = False
            self._ct400_recovery_input_matches = True
            self._ct400_recovery_disconnect_completed = False

        # Now that the device exists, pass it to the control panels
        self.control_panel.set_instrument(self.ct400_device)
        self.histogram_control.set_instrument(self.ct400_device)

        # Update UI visuals based on whether the device is real or dummy
        is_real_ct400 = isinstance(self.ct400_device, CT400)
        is_simulated_ct400 = isinstance(self.ct400_device, DummyCT400)
        # DummyCT400 exposes the same scan interface and is safe to operate in
        # development mode. Keep it unavailable to connection controls, but
        # allow scans and label their results as simulated below.
        self.control_panel.set_connected_laser_input(None)
        self.histogram_control.set_connected_laser_input(None)
        if is_simulated_ct400:
            self.control_panel.on_instrument_connected(True)
            self.histogram_control.on_instrument_connected(True)

        if old_device is not None and old_device is not device and isinstance(old_device, CT400):
            try:
                old_device.close()
            except Exception:
                logger.exception("Could not close replaced CT400 device.")

        if is_real_ct400:
            self._update_ct400_visuals(state=CT400Status.DISCONNECTED, message="CT400 Ready (Disconnected)")
        else:
            # The status was already set to UNAVAILABLE by the worker's error
            pass

        if is_simulated_ct400:
            self._refresh_global_status()

        self._sync_alignment_hardware()

    def _ct400_device_has_unresolved_laser_state(self) -> bool:
        return bool(
            self._ct400_scan_state_uncertain
            or self._ct400_connection_configured
            or self._ct400_cleanup_laser_input is not None
            or self._ct400_connected_laser_input is not None
            or self.is_ct400_connected_state
        )

    def _defer_ct400_device_replacement(self, device: AbstractCT400):
        previous = self._pending_ct400_device_replacement
        if previous is not None and previous is not device and isinstance(previous, CT400):
            try:
                previous.close()
            except Exception:
                logger.exception("Could not close superseded pending CT400 device.")
        self._pending_ct400_device_replacement = device
        if self._ct400_operation_state is CT400OperationState.IDLE:
            self._ct400_connection_operation_token += 1
            self._ct400_connected_laser_input = None
            self.control_panel.set_connected_laser_input(None)
            self.histogram_control.set_connected_laser_input(None)
            if self._ct400_scan_state_uncertain:
                if self._ct400_recovery_disconnect_completed:
                    state = CT400Status.RECOVERY_CONFIRMATION_REQUIRED
                    message = (
                        "Recovery Disconnect command returned; it does not independently confirm physical "
                        "safe-state. Follow the approved procedure, then explicitly confirm safe-state."
                    )
                else:
                    state = CT400Status.SCAN_STATE_UNCERTAIN
                    message = "CT400 scan state is uncertain; use operator-controlled recovery before replacement."
                self._update_ct400_visuals(state, message)
            elif self._ct400_cleanup_laser_input is not None:
                self._update_ct400_visuals(
                    CT400Status.DISCONNECT_UNCONFIRMED,
                    f"Replacement pending; disconnect the previously configured input "
                    f"{self._ct400_cleanup_laser_input.name} first.",
                )
            else:
                self._update_ct400_visuals(
                    CT400Status.DISCONNECT_UNCONFIRMED,
                    "CT400 state is uncertain and its configured input is unknown. "
                    "Follow the approved laboratory safe-state procedure.",
                )

    def _apply_pending_ct400_device_replacement(self):
        replacement = self._pending_ct400_device_replacement
        if replacement is None or self._ct400_operation_state is not CT400OperationState.IDLE:
            return
        if self._ct400_device_has_unresolved_laser_state():
            self._defer_ct400_device_replacement(replacement)
            return
        self._pending_ct400_device_replacement = None
        self._on_ct400_initialized(replacement)

    def _begin_lazy_init(self):
        """Starts all slow hardware initializations on background threads."""
        logger.info("Starting lazy initialization of hardware...")

        # 1. Start Piezo discovery (already asynchronous, good)
        # self._init_piezos_lazy()

        # 2. Start CT400 initialization (NOW asynchronous)
        self._init_ct400_lazy()

        # Start the proprietary Vimba system only when a physical camera is
        # explicitly configured. Simulated cameras use the same panel workflow
        # and remain available on driver-free development machines.
        needs_vimba = any(cam.enabled and cam.backend == "vimba" for cam in self.config.cameras.values())
        if needs_vimba:
            self._start_vimbasystem()
            if not self.vmb_instance:
                logger.error("VimbaSystem not active; physical camera initialization will report unavailable.")
        self._init_cameras_lazy()

    def _init_ct400_lazy(self):
        """Initializes the CT400 on a background thread."""
        if self._pending_init_close:
            logger.info("Skipping CT400 initialization while application close is pending.")
            return
        logger.info("Starting lazy initialization of CT400...")
        # 1. Create the worker
        worker = CT400InitWorker(config=self.config)

        # 2. Connect SPECIFIC signals (TaskRunner handles lifecycle signals)
        worker.ct400_initialized.connect(self._on_ct400_initialized)
        worker.status_updated.connect(self._on_ct400_status_updated)

        # TaskRunner owns the worker and thread for this one-shot operation.
        task = TaskRunner(worker)
        self.ct400_task = task
        task.worker_thread.finished.connect(lambda task=task: self._ct400_init_task_finished.emit(task))
        self._track_init_task(task)
        task.start()

    @Slot(object)
    def _on_ct400_init_task_finished(self, task):
        """Clear only the CT400 task whose thread just finished."""
        if self.ct400_task is task:
            self.ct400_task = None

    def _init_piezos_lazy(self):
        """Initializes the Piezo controllers on a background thread."""
        if self._pending_piezo_operation_close:
            logger.info("Skipping piezo initialization while application close is pending.")
            return
        if self._pending_init_close:
            logger.info("Skipping piezo initialization while application close is pending.")
            return
        if self._piezo_operations_in_flight:
            logger.info("Skipping piezo discovery while a piezo connection operation is active.")
            return
        if self._alignment_hardware_transition_blocked():
            logger.info("Skipping piezo discovery while alignment owns the hardware.")
            return
        logger.info("Starting lazy initialization of Piezo controllers...")

        worker = PiezoInitWorker(config=self.config.instruments)

        # Connect specific data signals
        worker.piezos_initialized.connect(self._on_piezos_initialized)
        worker.initialization_failed.connect(self._on_piezo_init_failed)

        # TaskRunner owns the worker and thread for this one-shot operation.
        task = TaskRunner(worker)
        self.piezo_task = task
        task.worker_thread.finished.connect(lambda task=task: self._piezo_init_task_finished.emit(task))
        self._track_init_task(task)
        task.start()

    def _track_init_task(self, task: TaskRunner):
        """Own an initialization task until its thread reaches its final boundary."""
        self._init_tasks.add(task)
        task.worker_thread.finished.connect(lambda task=task: self._init_task_thread_finished.emit(task))

    @Slot(object)
    def _on_init_task_thread_finished(self, task):
        """Release exactly the initialization task whose thread finished."""
        if task not in self._init_tasks:
            return
        self._init_tasks.remove(task)
        if self._pending_init_close and not self._init_tasks:
            logger.info("All initialization tasks finished; resuming deferred application close.")
            QTimer.singleShot(0, self.close)

    @Slot(object)
    def _on_piezo_init_task_finished(self, task):
        """Clear only the piezo task whose thread just finished."""
        if self.piezo_task is task:
            self.piezo_task = None

    def _start_vimbasystem(self):
        """Initializes and enters the main VimbaSystem context.

        This must be done once before any camera operations can occur.
        """
        if self.vmb_instance is not None:
            logger.info("VmbSystem already active.")
            return
        if not VIMBA_AVAILABLE:
            logger.warning("Vimba camera support is not installed; camera initialization is disabled.")
            self.vmb_instance = None
            return
        try:
            logger.info("Attempting to start VmbSystem...")
            self.vmb_instance = VmbSystem.get_instance()
            self.vmb_instance.__enter__()
            logger.info("VmbSystem entered successfully.")
        except VmbSystemError as e:
            logger.exception("Failed to enter VmbSystem")
            self.vmb_instance = None
            QMessageBox.critical(
                self,
                "Vimba System Error",
                f"Could not initialize Vimba API: {e}\nCameras will be unavailable.",
            )
        except Exception as e:
            logger.critical(f"Unexpected error starting VmbSystem: {e}", exc_info=True)
            self.vmb_instance = None
            QMessageBox.critical(
                self,
                "Vimba System Error",
                f"An unexpected error occurred while starting Vimba API: {e}\nCameras will be unavailable.",
            )

    def _cleanup_vimbasystem(self):
        """Exits the VimbaSystem context cleanly."""
        if self.vmb_instance:
            logger.info("Attempting to exit VmbSystem...")
            try:
                self.vmb_instance.__exit__(None, None, None)
                logger.info("VmbSystem exited successfully.")
            except VmbSystemError:
                logger.exception("Failed to exit VmbSystem")
            except Exception as e:
                logger.critical(f"Unexpected error exiting VmbSystem: {e}", exc_info=True)
            finally:
                self.vmb_instance = None

