    def _init_cameras_lazy(self):
        """Initializes all enabled cameras asynchronously.

        For each valid camera in the config, this method creates a placeholder
        UI panel, then spawns a dedicated worker thread (CameraInitWorker) to
        open the camera. This prevents the UI from freezing while waiting for
        multiple cameras to connect.
        """
        if self._shutdown_requested:
            return
        logger.info("Initializing cameras lazily...")
        if not all([self.camera_container, self.camera_layout, self.cameras_menu]):
            logger.error("UI components for camera initialization are not ready. Aborting.")
            return

        # Get a dictionary of valid camera configs, keyed by their identifier.
        camera_configs_to_init = {
            identifier: config
            for identifier, config in self.config.cameras.items()
            if self._should_initialize_camera(identifier, config)
        }

        if not camera_configs_to_init:
            no_cameras_action = QAction("No enabled cameras found in config", self)
            no_cameras_action.setEnabled(False)
            if self.cameras_menu is not None:
                self.cameras_menu.addAction(no_cameras_action)
            logger.info("No valid, enabled cameras to initialize.")
            return

        for identifier, config in camera_configs_to_init.items():
            logger.debug(f"Setting up initialization for camera '{config.name}' (ID: {identifier})")

            # 1. Create and add the placeholder panel to the UI
            placeholder_panel = self._create_camera_panel(None, config)
            self.camera_panels[identifier] = placeholder_panel
            self.camera_layout.addWidget(placeholder_panel)

        # Finish the entire GUI graph before any camera can publish a result
        # or destroy its initialization worker concurrently with construction.
        for identifier, config in camera_configs_to_init.items():
            # Create Worker
            worker = CameraInitWorker(identifier=identifier, cam_config=config)
            worker.camera_initialized.connect(self._on_camera_initialized)

            # Create Runner
            task = TaskRunner(worker)

            self._track_init_task(task)
            task.start()

    @Slot(str, object, CameraConfig)
    def _on_camera_initialized(self, identifier: str, camera_instance: VimbaCam | None, cam_config: CameraConfig):
        """Slot to handle a camera that has finished initializing.

        This method is called when a `CameraInitWorker` finishes. If the camera
        was initialized successfully, it connects the camera's signals to the
        UI panel, adds it to the list of active cameras, and creates a menu
        action for it. If it failed, it updates the panel to show an error state.

        Args:
            identifier: The unique ID of the camera that was initialized.
            camera_instance: The live `VimbaCam` object if successful, else `None`.
            cam_config: The configuration object for the camera.
        """
        if camera_instance is not None:
            camera_instance.setParent(self)
        if self._shutdown_requested:
            if camera_instance is not None:
                camera_instance.close()
                camera_instance.deleteLater()
            return
        panel = self.camera_panels.get(identifier)  # Find panel by identifier
        if not panel:
            logger.error(f"Could not find panel for camera config: {cam_config.name}")
            if camera_instance:
                camera_instance.close()
            return

        if isinstance(camera_instance, SimulatedCamera) and not camera_instance.open():
            camera_instance.close()
            camera_instance = None

        if camera_instance:
            logger.info(f"Camera '{cam_config.name}' is online. Connecting to UI.")
            self.cameras.append(camera_instance)

            panel.set_camera(camera_instance)
            self._connect_camera_signals(camera_instance, panel)
            panel.status_changed.connect(self._refresh_global_status)
            panel._arm_watchdog()

            panel.video_label.setText(MSG_CAMERA_WAITING)
        else:
            logger.error(f"Failed to initialize camera '{cam_config.name}'.")
            error_msg = f"{cam_config.name}\n(Failed to Open)"
            panel.video_label.setText(error_msg)
            panel.video_label.setStyleSheet("background-color: #ffebee; color: #c62828;")
        self._refresh_global_status()

    def _should_initialize_camera(self, identifier: str, cam_config: CameraConfig) -> bool:
        """Checks if a camera from the config should be initialized."""
        if not cam_config.enabled:
            logger.info(f"Skipping disabled camera: {cam_config.name}")
            return False
        if not identifier or identifier.startswith("PUT_"):
            logger.warning(f"Skipping camera '{cam_config.name}': Invalid or placeholder identifier.")
            error_msg = f"{cam_config.name}\n(Config Error: Invalid ID)"
            placeholder = self._create_camera_error_placeholder(error_msg)
            self.camera_layout.addWidget(placeholder)
            return False
        return True

    def _create_and_open_camera(self, cam_config: CameraConfig) -> VimbaCam | None:
        """Creates a VimbaCam instance and attempts to open it. Returns instance or None."""
        try:
            cam_instance = VimbaCam(
                identifier=cam_config.identifier,
                camera_name=cam_config.name,
                flip_horizontal=cam_config.flip_horizontal,
                parent=self,
            )
            if not cam_instance.open():
                logger.error(f"Failed to open camera {cam_config.name} (ID: {cam_config.identifier}).")
                error_msg = MSG_CAMERA_FAILED.format(cam_config.name)
                placeholder = self._create_camera_error_placeholder(error_msg)
                self.camera_layout.addWidget(placeholder)
                cam_instance.close()  # Clean up the failed instance
                return None
            return cam_instance
        except VmbCameraError as e:
            logger.error(f"Vimba Error initializing camera {cam_config.name} (ID: {cam_config.identifier}): {e}")
            error_msg = f"{cam_config.name}\n(Vimba Error)"
            placeholder = self._create_camera_error_placeholder(error_msg)
            self.camera_layout.addWidget(placeholder)
            return None
        except Exception:
            logger.exception(
                f"Unexpected error creating camera instance {cam_config.name}",
            )
            error_msg = f"{cam_config.name}\n(Init Error)"
            placeholder = self._create_camera_error_placeholder(error_msg)
            self.camera_layout.addWidget(placeholder)
            return None

    def _create_camera_panel(self, cam_instance: VimbaCam | None, cam_config: CameraConfig) -> CameraPanel:
        title = f"{cam_config.name} [SIMULATED]" if cam_config.backend == "simulation" else cam_config.name
        panel = CameraPanel(
            cam_instance,
            title,
            config=cam_config,
            parent=self.camera_container,
            settings=self.settings,
        )
        panel.set_controls_visibility(self.settings.camera_controls_visible(cam_config.identifier))
        if not cam_instance:
            panel.video_label.setText(MSG_CAMERA_CONNECTING.format(cam_config.name))

        # --- NEW: Connect double-click signal ---
        panel.maximize_requested.connect(self.toggle_cinema_mode)
        # ----------------------------------------

        return panel

    def _connect_camera_signals(self, cam_instance: VimbaCam, panel: CameraPanel):
        """Connects signals between a camera instance and its UI panel."""
        # The connection to the worker is now handled inside CameraPanel.
        # We only need to connect the signals that the panel itself consumes.

        # FPS is recalculated at the camera's ~0.5 s cadence and serves as the
        # low-rate activity heartbeat for recovery/watchdog state.
        cam_instance.fps_updated.connect(panel.update_fps)
        cam_instance.error.connect(panel._handle_camera_error_message)
        panel.recovery_requested.connect(self._request_camera_recovery)
        panel.auto_operation_finished.connect(self._on_camera_auto_operation_finished)

    @Slot(str)
    def _request_camera_recovery(self, identifier: str):
        """Own at most one recovery TaskRunner per camera identifier."""
        if (
            self._shutdown_requested
            or identifier in self._camera_recovery_tasks
            or self._pending_camera_lifecycle_close
        ):
            return
        camera = next((candidate for candidate in self.cameras if candidate.identifier == identifier), None)
        panel = self.camera_panels.get(identifier)
        if camera is None or panel is None:
            return

        worker = CameraRecoveryWorker(camera, identifier)
        task = TaskRunner(worker)
        self._camera_recovery_tasks[identifier] = task
        self._refresh_global_status()
        worker.task = task
        worker.recovery_finished.connect(self._on_camera_recovery_result)
        task.worker_thread.finished.connect(
            lambda camera_id=identifier, task=task: self._camera_recovery_thread_finished.emit(camera_id, task)
        )
        task.start()

    @Slot(str, bool, str, object)
    def _on_camera_recovery_result(self, identifier: str, success: bool, message: str, task: TaskRunner):
        current_task = self._camera_recovery_tasks.get(identifier)
        if current_task is not None and current_task is not task:
            return
        panel = self.camera_panels.get(identifier)
        if panel is None:
            return
        if success:
            panel.recovery_succeeded()
        else:
            panel.recovery_failed(message)
        self._refresh_global_status()

    def _on_camera_recovery_thread_finished(self, identifier: str, task: TaskRunner):
        """Release ownership only at the exact QThread.finished boundary."""
        if self._camera_recovery_tasks.get(identifier) is task:
            del self._camera_recovery_tasks[identifier]
        self._refresh_global_status()
        self._resume_close_after_camera_lifecycle_if_ready()

    @Slot()
    def _on_camera_auto_operation_finished(self):
        self._resume_close_after_camera_lifecycle_if_ready()

    def _camera_lifecycle_busy(self) -> bool:
        return bool(self._camera_recovery_tasks) or any(
            panel.auto_operation_active or getattr(panel, "_camera_mode_change_active", False)
            for panel in self.camera_panels.values()
        )

    def _resume_close_after_camera_lifecycle_if_ready(self):
        if self._pending_camera_lifecycle_close and not self._camera_lifecycle_busy():
            QTimer.singleShot(0, self, self.close)

    def _create_camera_error_placeholder(self, message: str) -> QWidget:
        """Helper to create a consistent placeholder for camera errors."""
        placeholder_widget = QFrame()
        placeholder_widget.setObjectName("cameraErrorPlaceholder")
        placeholder_widget.setStyleSheet(
            "QFrame#cameraErrorPlaceholder {"
            "  border: 1px solid #ffcdd2;"
            "  border-radius: 5px;"
            "  background-color: #ffebee;"
            "}"
            "QLabel { color: #c62828; font-weight: normal; background: transparent; }"
        )
        placeholder_widget.setMinimumSize(220, 120)
        placeholder_widget.setMaximumWidth(350)
        placeholder_widget.setSizePolicy(QSizePolicy.Policy.Preferred, QSizePolicy.Policy.Preferred)

        layout = QVBoxLayout(placeholder_widget)
        layout.setContentsMargins(10, 10, 10, 10)
        layout.setSpacing(5)

        icon_label = QLabel()
        try:
            std_icon = self.style().standardIcon(QtWidgets.QStyle.StandardPixmap.SP_MessageBoxWarning)
            if not std_icon.isNull():
                icon_label.setPixmap(std_icon.pixmap(QSize(32, 32)))
        except Exception as e_icon:  # noqa: BLE001  # Preserve best-effort platform and hardware cleanup.
            logger.warning(f"Could not load standard warning icon: {e_icon}")
            icon_label.setText("⚠️")
            icon_label.setFont(QFont("Segoe UI Symbol", 20))

        icon_label.setAlignment(Qt.AlignmentFlag.AlignCenter)

        text_label = QLabel(message)
        text_label.setAlignment(Qt.AlignmentFlag.AlignCenter)
        text_label.setWordWrap(True)

        layout.addWidget(icon_label)
        layout.addWidget(text_label)

        placeholder_widget.setToolTip(f"Camera Initialization Error: {message.replace('\n', ' ')}")
        return placeholder_widget

